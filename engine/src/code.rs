//! Code for the code index: a source file, a repo's doc or a notebook, cut into stretches of whole lines (a notebook's
//! into whole cells) that the model reads one at a time, each knowing where it is, so that a result opens there. And
//! names in code: a query that's a name finds the place that defines it rather than every place that uses it.
use crate::extract::ExtractError;
use crate::model::IndexOptions;
use crate::paths;
use crate::rules;
use regex::Regex;
use std::path::Path;
use std::sync::LazyLock;

/// A stretch of a file: its text, and its first and last lines (or cells), from 1.
#[derive(Debug, PartialEq, Eq)]
pub struct Piece {
    pub text: String,
    pub first: usize,
    pub last: usize,
}

pub struct CodeFile {
    pub pieces: Vec<Piece>,
    /// For the model, the file's title: its path in its repo ("billing/payments/retry.py").
    pub title: String,
    /// The repo (or code project) it's in, if any.
    pub repo: Option<String>,
    pub lines: usize,
    /// A notebook's cells (code and notes; outputs are never read). None for anything else.
    pub cells: Option<usize>,
}

/// The model reads 2,048 tokens of an input at most; a single line longer than this is cut here.
const LONGEST_PIECE: usize = 4000;

pub fn read(path: &str, options: &IndexOptions) -> Result<CodeFile, ExtractError> {
    let data = std::fs::read(path)?;
    let (repo, title) = place(path);
    if paths::extension(path) == "ipynb" {
        let cells = notebook_cells(&data)?;
        let text = cells.join("\n");
        if text.len() as u64 > options.max_code_bytes {
            return Err(ExtractError::LeftOut(format!("cells over {} MB", options.max_code_bytes >> 20)));
        }
        check(&text, true)?;
        let lines = line_count(&text);
        let count = cells.len();
        return Ok(CodeFile { pieces: cells_pieces(&cells, options.code_stretch), title, repo, lines, cells: Some(count) });
    }
    if data[..data.len().min(8000)].contains(&0) {
        return Err(ExtractError::LeftOut("not text".into()));
    }
    let text = String::from_utf8(data).unwrap_or_else(|error| error.into_bytes().iter().map(|&b| b as char).collect());
    check(&text, rules::SOURCE_EXTENSIONS.contains(&paths::extension(path).as_str()))?;
    Ok(CodeFile { pieces: lines(&text, options.code_stretch), title, repo, lines: line_count(&text), cells: None })
}

/// Code that's no use to read: it holds a private key, or (`source`: code, not a repo's notes) a program wrote it or
/// it's minified.
fn check(text: &str, source: bool) -> Result<(), ExtractError> {
    if text.contains("PRIVATE KEY-----") {
        return Err(ExtractError::LeftOut("holds a private key".into()));
    }
    if !source {
        return Ok(());
    }
    let top: String = text.chars().take(1000).collect();
    for mark in ["DO NOT EDIT", "@generated", "Code generated by", "Autogenerated by", "Generated by the protocol"] {
        if top.contains(mark) {
            return Err(ExtractError::LeftOut(format!("made by a program (“{mark}”)")));
        }
    }
    // Minified: few lines, and long ones (a bundle can be one line of 100,000 characters).
    let (lines, characters) = (line_count(text).max(1), text.chars().count());
    if characters / lines > 300 && text.split('\n').any(|line| line.chars().count() > 3000) {
        return Err(ExtractError::LeftOut(format!("minified ({} characters a line)", characters / lines)));
    }
    Ok(())
}

pub fn line_count(text: &str) -> usize {
    let count = text.bytes().filter(|&b| b == b'\n').count();
    if text.ends_with('\n') || text.is_empty() { count } else { count + 1 }
}

/// Lines that close a block (shell, Ruby, Lua, Objective-C, the C preprocessor).
const CLOSERS: [&str; 8] = ["end", "fi", "done", "esac", "@end", "#endif", "end;", "end)"];

fn split_lines(text: &str) -> Vec<&str> {
    text.split('\n').map(|line| line.strip_suffix('\r').unwrap_or(line)).collect()
}

/// Stretches of whole lines, each at most `size` characters (a longer line is a stretch of its own). A stretch ends,
/// when it can, where the code does: before a line that starts a new block at the left margin, or after a blank line,
/// in its last 60%. One that had to stop in the middle of a block hands its last two lines on to the next.
pub fn lines(text: &str, size: usize) -> Vec<Piece> {
    let mut lines = split_lines(text);
    if lines.last() == Some(&"") {
        lines.pop();   // the final newline
    }
    let count = lines.len();
    let mut offsets = Vec::with_capacity(count + 1);   // characters before each line (each with its newline)
    offsets.push(0);
    for line in &lines {
        offsets.push(offsets.last().unwrap() + line.chars().count() + 1);
    }
    let blank = |index: usize| lines[index].chars().all(char::is_whitespace);
    let starts_block = |index: usize| {
        let Some(first) = lines[index].chars().next() else { return false };
        if first.is_whitespace() {
            return false;
        }
        // A closing line belongs to the block above it.
        !"})]".contains(first) && !CLOSERS.contains(&lines[index].trim())
    };
    let mut pieces = vec![];
    let mut start = 0;
    while start < count {
        while start < count && blank(start) {
            start += 1;
        }
        if start >= count {
            break;
        }
        let mut end = start + 1;   // the stretch is lines[start..end]
        while end < count && offsets[end + 1] - offsets[start] <= size {
            end += 1;
        }
        let mut natural = end >= count;
        if !natural {
            // Where the code breaks by itself, keeping at least 40% of a stretch: a new block after a blank line
            // first, then any blank line or new block.
            let floor = offsets[start] + size * 2 / 5;
            let last_break = |is_break: &dyn Fn(usize) -> bool| -> Option<usize> {
                let mut line = end;
                while line > start + 1 && offsets[line] >= floor {
                    if is_break(line) {
                        return Some(line);
                    }
                    line -= 1;
                }
                None
            };
            let cut = last_break(&|l| starts_block(l) && blank(l - 1))
                .or_else(|| last_break(&|l| blank(l - 1) || starts_block(l)));
            if let Some(cut) = cut {
                end = cut;
                natural = true;
            }
        }
        let mut last = end;
        while last > start + 1 && blank(last - 1) {
            last -= 1;   // blank lines at its end don't count
        }
        let mut body = lines[start..last].join("\n");
        if body.chars().count() > LONGEST_PIECE {
            body = body.chars().take(LONGEST_PIECE).collect();
        }
        pieces.push(Piece { text: body, first: start + 1, last });
        start = if natural { end } else { (end.saturating_sub(2)).max(start + 1) };
    }
    pieces
}

const SUMMARY_SKIPS: [&str; 13] = ["//", "#", "/*", "*", "--", "\"\"\"", "import ", "from ", "#include", "using ",
                                   "package ", "}", ")"];

/// A stretch in one line, for result lists: its first line that defines something ("def retry_with_backoff(…"),
/// else its first line of code (not a comment, an import or a closing brace).
pub fn summary(text: &str) -> String {
    let lines: Vec<&str> = split_lines(text).into_iter().map(str::trim).filter(|l| !l.is_empty()).collect();
    let definition = lines.iter().find(|line| line.split_whitespace().take(4).any(defines_something));
    let code = lines.iter().find(|line| !SUMMARY_SKIPS.iter().any(|skip| line.starts_with(skip)) && !line.starts_with('@'));
    let line = definition.or(code).or(lines.first()).copied().unwrap_or("");
    if line.chars().count() > 160 { format!("{}…", line.chars().take(160).collect::<String>()) } else { line.to_string() }
}

/// The cells of a Jupyter notebook, code and notes alike, as their text. Outputs aren't read.
fn notebook_cells(data: &[u8]) -> Result<Vec<String>, ExtractError> {
    let notebook: serde_json::Value =
        serde_json::from_slice(data).map_err(|_| ExtractError::Unreadable("not a notebook".into()))?;
    // nbformat 4 keeps its cells at the top; nbformat 3 inside worksheets, with code in "input".
    let cells = notebook["cells"].as_array().or_else(|| notebook["worksheets"][0]["cells"].as_array())
        .cloned().unwrap_or_default();
    Ok(cells.iter().map(|cell| {
        let source = if cell.get("source").is_some() { &cell["source"] } else { &cell["input"] };
        match source {
            serde_json::Value::Array(parts) => parts.iter().filter_map(|p| p.as_str()).collect::<String>(),
            serde_json::Value::String(text) => text.clone(),
            _ => String::new(),
        }
    }).collect())
}

/// Whole cells to a stretch, up to `size` characters; a longer cell is cut into stretches of lines that all point at
/// it. Empty cells are passed over.
fn cells_pieces(cells: &[String], size: usize) -> Vec<Piece> {
    let mut pieces = vec![];
    let (mut text, mut first, mut last) = (String::new(), 0, 0);
    let flush = |text: &mut String, first: usize, last: usize, pieces: &mut Vec<Piece>| {
        if !text.is_empty() {
            pieces.push(Piece { text: std::mem::take(text), first, last });
        }
    };
    for (index, cell) in cells.iter().enumerate() {
        let body = cell.trim();
        if body.is_empty() {
            continue;
        }
        let number = index + 1;
        let length = body.chars().count();
        if length > size {
            flush(&mut text, first, last, &mut pieces);
            pieces.extend(lines(body, size).into_iter().map(|p| Piece { text: p.text, first: number, last: number }));
            continue;
        }
        if !text.is_empty() && text.chars().count() + 2 + length > size {
            flush(&mut text, first, last, &mut pieces);
        }
        if text.is_empty() {
            first = number;
            text = body.to_string();
        } else {
            text.push_str("\n\n");
            text.push_str(body);
        }
        last = number;
    }
    flush(&mut text, first, last, &mut pieces);
    pieces
}

/// The repo (or code project) `path` is in, and the file's title: its path from the repo's folder, the repo's name
/// first. Outside any: its folder's name and its own.
pub fn place(path: &str) -> (Option<String>, String) {
    let home = paths::home_string();
    let mut folder = paths::parent(path).to_string();
    while folder.len() > 1 && folder != home {
        if Path::new(&format!("{folder}/.git")).exists() || rules::is_project_root(&folder) {
            let parent = paths::parent(&folder);
            let title = path[parent.len() + usize::from(parent != "/")..].to_string();
            return (Some(folder), title);
        }
        folder = paths::parent(&folder).to_string();
    }
    let parts: Vec<&str> = path.split('/').filter(|p| !p.is_empty()).collect();
    (None, parts[parts.len().saturating_sub(2)..].join("/"))
}

// MARK: Names in code

static IDENTIFIER: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"^[A-Za-z_$][A-Za-z0-9_$]*(?:(?:\.|::|->|#)[A-Za-z_$][A-Za-z0-9_$]*)*$").unwrap()
});

/// The words keyword search keeps a name from code as ("quantize_row_q8_0_ref" → quantize row q8 0 ref, as one
/// phrase), when the query is one: snake_case, camelCase, dotted, or with digits. None for words anyone would say.
pub fn identifier(query: &str) -> Option<Vec<String>> {
    let name = query.trim();
    let name = name.strip_suffix("()").unwrap_or(name);
    if !IDENTIFIER.is_match(name) {
        return None;
    }
    let camel = name.chars().skip(1).any(char::is_uppercase) && name.chars().any(char::is_lowercase);
    if !camel && !name.chars().any(|c| "_.:#$".contains(c) || c.is_ascii_digit()) {
        return None;
    }
    Some(name.to_lowercase().split(|c: char| !c.is_alphanumeric()).filter(|w| !w.is_empty()).map(str::to_string).collect())
}

/// The keyword search pattern for an identifier's words: one phrase, so they match only side by side.
pub fn phrase(words: &[String]) -> String {
    format!("\"{}\"", words.join(" "))
}

const DEFINERS: [&str; 31] = [
    "def", "func", "fn", "fun", "function", "class", "struct", "enum", "protocol", "interface", "trait", "type",
    "typealias", "actor", "extension", "impl", "module", "namespace", "object", "record", "macro", "const", "let",
    "var", "val", "union", "mod", "sub", "@interface", "@implementation", "@protocol",
];
const MORE_DEFINERS: [&str; 2] = ["#define", "function*"];
/// Words before a name that mean it's being used, not defined.
const USERS: [&str; 28] = [
    "return", "await", "yield", "throw", "new", "else", "case", "print", "echo", "assert", "not", "and", "or", "in",
    "is", "do", "go", "defer", "try", "catch", "if", "while", "for", "typeof", "delete", "raise", "import", "from",
];

fn is_definer(word: &str) -> bool {
    DEFINERS.contains(&word) || MORE_DEFINERS.contains(&word)
}

/// A word that starts a definition ("def", "func", "class", "@implementation"…).
pub fn defines_something(word: &str) -> bool {
    is_definer(word) && !["let", "var", "const", "val"].contains(&word)
}

fn is_name_char(c: char) -> bool {
    c.is_alphanumeric() || c == '_' || c == '$'
}

/// Where `name` is in `line` as a whole name (not a part of a longer one), whatever its case: character ranges.
fn occurrences(name: &[char], line: &[char]) -> Vec<(usize, usize)> {
    let mut found = vec![];
    if name.is_empty() || name.len() > line.len() {
        return found;
    }
    let mut start = 0;
    while start + name.len() <= line.len() {
        let same = line[start..start + name.len()].iter().zip(name)
            .all(|(a, b)| a.to_lowercase().eq(b.to_lowercase()));
        if same {
            let end = start + name.len();
            let clear_before = start == 0 || !is_name_char(line[start - 1]);
            let clear_after = end == line.len() || !is_name_char(line[end]);
            if clear_before && clear_after {
                found.push((start, end));
            }
            start = end;
        } else {
            start += 1;
        }
    }
    found
}

fn definition_strength(before: &str, after: &str, line: &str) -> u8 {
    let previous = before.split_whitespace().last().unwrap_or("");
    if is_definer(previous) {
        return 2;
    }
    if before.starts_with("func (") && before.ends_with(')') {
        return 2;   // a Go method
    }
    if before.starts_with("- (") || before.starts_with("+ (") {
        // An Objective-C method.
        return if after.starts_with(':') || after.is_empty() || after.starts_with('{') || after.starts_with(';') { 2 } else { 0 };
    }
    // C-style: "static void name(…) {", "struct gguf_context * name(…)", not a call or an assignment.
    let Some(last) = before.chars().last() else { return 0 };
    if !after.starts_with('(') || USERS.contains(&previous) || before.chars().any(|c| "=(,.!?".contains(c))
        || before.contains("->") || !(last.is_alphanumeric() || "*&>_]".contains(last)) {
        return 0;
    }
    if line.trim().ends_with(';') { 1 } else { 2 }
}

/// Where `name` is defined in `text` (a stretch whose first line is `first`): the line, and how surely (2 after a
/// word that defines something or as a C-style definition, 1 for a declaration). None when the stretch only uses it.
pub fn definition(name: &str, text: &str, first: usize) -> Option<(usize, u8)> {
    let name: Vec<char> = name.chars().collect();
    let mut best: Option<(usize, u8)> = None;
    for (offset, line) in split_lines(text).into_iter().enumerate() {
        let chars: Vec<char> = line.chars().collect();
        for (start, end) in occurrences(&name, &chars) {
            let before: String = chars[..start].iter().collect();
            let after: String = chars[end..].iter().collect();
            let strength = definition_strength(before.trim(), after.trim(), line);
            if strength > best.map_or(0, |b| b.1) {
                best = Some((first + offset, strength));
            }
            if strength == 2 {
                return best;
            }
        }
    }
    best
}

const COMMENT_STARTS: [&str; 9] = ["//", "#", "/*", "*", "--", "\"\"\"", "'''", "<!--", ";"];

/// Whether `line` has `word` (lowercased) as a word or as the start of a name's part (the "retry" of
/// retryWithBackoff and retry_with_backoff).
fn has(word: &[char], line: &[char]) -> bool {
    let lower: Vec<char> = line.iter().map(|c| c.to_lowercase().next().unwrap_or(*c)).collect();
    if word.is_empty() || word.len() > lower.len() {
        return false;
    }
    (0..=lower.len() - word.len()).any(|at| {
        lower[at..at + word.len()] == *word
            && (at == 0 || !(lower[at - 1].is_alphabetic() || lower[at - 1].is_numeric()) || line[at].is_uppercase())
    })
}

/// The line (from `first`) to open at for `words`: the first with one of them that defines something, else the first
/// such line of code (not a comment), else the first such line. None when none is there.
pub fn first_line(words: &[String], text: &str, first: usize) -> Option<usize> {
    let words: Vec<Vec<char>> = words.iter().filter(|w| w.chars().count() >= 2)
        .map(|w| w.to_lowercase().chars().collect()).collect();
    if words.is_empty() {
        return None;
    }
    let (mut first_code, mut first_any) = (None, None);
    for (offset, line) in split_lines(text).into_iter().enumerate() {
        let chars: Vec<char> = line.chars().collect();
        if !words.iter().any(|w| has(w, &chars)) {
            continue;
        }
        let trimmed = line.trim();
        if trimmed.split_whitespace().take(4).any(defines_something) {
            return Some(first + offset);
        }
        if first_code.is_none() && !COMMENT_STARTS.iter().any(|c| trimmed.starts_with(c)) {
            first_code = Some(offset);
        }
        first_any.get_or_insert(offset);
    }
    first_code.or(first_any).map(|offset| first + offset)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cuts_code_where_it_breaks() {
        let code = (0..60).map(|i| format!("def f{i}():\n    return {i}\n\n")).collect::<String>();
        let pieces = lines(&code, 300);
        assert!(pieces.len() > 5);
        assert!(pieces.iter().all(|p| p.text.starts_with("def ")));
        assert_eq!(pieces[0].first, 1);
    }

    #[test]
    fn finds_names_and_definitions() {
        assert_eq!(identifier("quantize_row_q8_0_ref").unwrap(), ["quantize", "row", "q8", "0", "ref"]);
        assert_eq!(identifier("refreshAccessToken()").unwrap(), ["refreshaccesstoken"]);
        assert_eq!(identifier("retry"), None);
        let text = "x = retry_with_backoff(3)\n\ndef retry_with_backoff(n):\n    pass";
        assert_eq!(definition("retry_with_backoff", text, 10), Some((12, 2)));
        assert_eq!(first_line(&["backoff".into()], "# backoff\ncall(backoff)\n", 1), Some(2));
        assert_eq!(summary("import os\n\n# x\ndef main():\n  pass"), "def main():");
    }
}
